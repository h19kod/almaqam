export type Step =
  | { kind: 'text'; title: string; body: string }
  | { kind: 'listen'; title: string; body: string; play: { label: string; cents: number[] }[] }
  | { kind: 'ladder'; title: string; body: string; maqam: MaqamId };

export type Question =
  | { kind: 'choice'; prompt: string; options: string[]; answer: number; explain: string }
  | { kind: 'brick'; prompt: string; maqam: MaqamId; answer: number; explain: string }
  | { kind: 'maqam'; prompt: string; play: MaqamId; options: MaqamId[]; explain: string };

export interface Lesson { id: string; title: string; summary: string; maqam?: MaqamId; steps: Step[]; quiz: Question[] }

