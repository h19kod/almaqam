/** Arabic note names by cents above C3 (24-tone positions). */
const NAMES: Record<number, string> = {
  [-500]: 'يكاه', [-300]: 'عشيران', [-200]: 'عجم عشيران', [-150]: 'عراق', [-100]: 'كوشت',
  0: 'راست', 100: 'زركلاه', 200: 'دوكاه', 300: 'كرد', 350: 'سيكاه', 400: 'بوسليك', 500: 'جهاركاه',
  550: 'نيم حجاز', 600: 'حجاز', 700: 'نوى', 800: 'حصار', 850: 'تيك حصار', 900: 'حسيني', 1000: 'عجم',
  1050: 'أوج', 1100: 'ماهور', 1200: 'كردان', 1300: 'شهناز', 1400: 'محيّر', 1500: 'سنبلة', 1550: 'بزرك',
  1600: 'حسيني شوري', 1700: 'ماهوران', 1800: 'جواب حجاز', 1900: 'رمل توتي', 2000: 'جواب حصار',
  2100: 'جواب حسيني', 2200: 'جواب عجم', 2250: 'جواب أوج', 2300: 'جواب ماهور', 2400: 'جواب كردان',
  2550: 'جواب بزرك', 2600: 'جواب محيّر',
};

export function noteName(cents: number): string {
  const c = Math.round(cents / 50) * 50;
  if (NAMES[c]) return NAMES[c];
  return c >= 1200 && NAMES[c - 1200] ? `جواب ${NAMES[c - 1200]}` : '';
}

/** Absolute pitch (cents above C3) of a degree index; 7 degrees per octave. */
export function degreeCents(m: Maqam, d: number): number {
  const oct = Math.floor(d / 7);
  return m.tonic + oct * 1200 + m.steps[d % 7];
}

export function intervalLabel(c: number): string {
  if (c === 100) return 'نصف';
  if (c === 150) return 'ثلاثة أرباع';
  if (c === 200) return 'تون';
  if (c === 250) return 'تون وربع';
  if (c === 300) return 'تون ونصف';
  return `${c} سنت`;
}

export const DEGREES_IN_STUDIO = 15; // two octaves + one

/** Arabic count agreement for "نغمة". */
export function notesCount(n: number): string {
  if (n === 1) return 'نغمة واحدة';
  if (n === 2) return 'نغمتان';
  if (n >= 3 && n <= 10) return `${n} نغمات`;
  return `${n} نغمة`;
}

export function duration(ms: number): string {
  const s = Math.round(ms / 1000);
  if (s < 1) return 'أقل من ثانية';
  if (s === 1) return 'ثانية واحدة';
  if (s === 2) return 'ثانيتين';
  if (s <= 10) return `${s} ثوانٍ`;
  return `${s} ثانية`;
}
